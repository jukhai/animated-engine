const wordList = words.split('\n');

let attempts = 0;
let currentGuessInputs = []; // To store references to the input elements in the current row

// Function to create a single row of cells, with inputs if it's the active row
function createRow(rowIndex) {
    const rowDiv = document.createElement('div');
    rowDiv.classList.add('board-row');
    const board = document.getElementById('board');

    for (let j = 0; j < maxLength; j++) {
        const cell = document.createElement('div');
        cell.classList.add('cell');

        if (rowIndex === attempts) { // Only add input fields to the current guess row
            const input = document.createElement('input');
            input.type = 'text';
            input.maxLength = 1;
            input.classList.add('cell-input');
            input.dataset.row = rowIndex;
            input.dataset.col = j;
            cell.appendChild(input);
            currentGuessInputs.push(input);

            // Event listener for input
            input.addEventListener('input', handleInput);
            // Event listener for keydown (for backspace and Enter)
            input.addEventListener('keydown', handleKeydown);
        }
        rowDiv.appendChild(cell);
    }
    board.appendChild(rowDiv);
}

// Function to initialize the entire board
function initializeBoard() {
    const board = document.getElementById('board');
    board.innerHTML = ''; // Clear any existing content
    currentGuessInputs = []; // Reset current guess inputs

    for (let i = 0; i < guessAttemps; i++) {
        createRow(i);
    }

    // Focus the first input of the current row
    if (currentGuessInputs.length > 0) {
        currentGuessInputs[0].focus();
    }
}

function handleInput(event) {
    const input = event.target;
    const col = parseInt(input.dataset.col);

    // Convert to lowercase and ensure only one character
    input.value = input.value.toLowerCase().slice(0, 1);

    if (input.value.length === 1) {
        // Move focus to the next input if available
        if (col < maxLength - 1) {
            currentGuessInputs[col + 1].focus();
        } else {
            // If it's the last character, keep focus on it,
            // submission will happen on Enter key press.
        }
    }
}

function handleKeydown(event) {
    const input = event.target;
    const col = parseInt(input.dataset.col);

    if (event.key === 'Backspace') {
        if (input.value === '' && col > 0) {
            // If current input is empty, move focus to previous and clear it
            currentGuessInputs[col - 1].focus();
            currentGuessInputs[col - 1].value = ''; // Clear previous cell
        } else if (input.value !== '') {
            // If current input has a value, just clear it
            input.value = '';
        }
        event.preventDefault(); // Prevent default backspace behavior (e.g., navigating back)
    }  else if(event.key === 'Enter') {
        
        submitGuess(); 
        event.preventDefault(); // Prevent default Enter behavior (e.g., form submission)
    } else if (event.key.length === 1 && event.key.match(/[a-z0-9]/i)) {
        // Allow typing letters, handleInput will manage value and focus
    } else {
        // Prevent other keys from being typed into the input
        event.preventDefault();
    }
}
function submitGuess() {
    const messageElement = document.getElementById('message');
    const message1Element = document.getElementById('message1');

    if (attempts >= guessAttemps) {
        messageElement.textContent = 'No more attempts left!';
        return;
    }

    // Construct the guess from the current row's input values
    let guess = '';
    for (let i = 0; i < maxLength; i++) {
        const input = currentGuessInputs[i];
        if (input && input.value.length === 1) {
            guess += input.value;
        } else {
            messageElement.textContent = 'Please fill all 5 characters.';
            return; // Stop if any input is empty
        }
    }

    if (guess.length !== maxLength) {
        messageElement.textContent = 'Please enter a 5-character word.';
        return;
    }

    // New logic: Check if the guess is in the wordList
    if (!wordList.includes(guess)) {
        messageElement.textContent = `'${guess}'bô chit khóan, têng phah`;
        // Do NOT clear the input fields or change focus here.
        // The user will correct their existing input.
        return; // Stop submission if the word is not in the list
    }

    // Get the cells of the current guess row
    const currentRowCells = document.querySelectorAll(`.board-row:nth-child(${attempts + 1}) .cell`);

    const targetLetters = targetWord.split('');
    const guessLetters = guess.split('');
    const matchedIndices = new Set(); // To track letters in targetWord that have been matched

    // Create a mutable copy of targetLetters for tracking available letters
    const tempTargetLetters = [...targetLetters];

    // First pass: mark correct positions (green)
    for (let i = 0; i < maxLength; i++) {
        const cell = currentRowCells[i];
        const inputElement = cell.querySelector('.cell-input');

        if (guessLetters[i] === tempTargetLetters[i]) {
            cell.classList.add('correct');
            // Remove the input field and display the letter
            if (inputElement) {
                cell.removeChild(inputElement);
            }
            cell.textContent = guessLetters[i];
            tempTargetLetters[i] = null; // Mark as used
        }
    }

    // Second pass: mark presents (yellow) and absents (gray)
    for (let i = 0; i < maxLength; i++) {
        const cell = currentRowCells[i];
        // If it's already marked 'correct', skip
        if (cell.classList.contains('correct')) {
            continue;
        }

        const inputElement = cell.querySelector('.cell-input');
        // Remove the input field and display the letter
        if (inputElement) {
            cell.removeChild(inputElement);
        }
        cell.textContent = guessLetters[i]; // Ensure text content is set for all cells

        const letter = guessLetters[i];
        const targetIndex = tempTargetLetters.indexOf(letter);

        if (targetIndex !== -1) {
            cell.classList.add('present');
            tempTargetLetters[targetIndex] = null; // Mark as used
        } else {
            cell.classList.add('absent');
        }
    }

    attempts++;

    if (guess === targetWord) {
        messageElement.textContent = 'Kiong-hí Lí ioh tio̍h ah! Pe̍h-ōe-jī chhut-thâu-thiⁿ';
        message1Element.textContent = '(Beh koh ioh, ji̍h F5)';
        // Disable all inputs if game is won
        // Find all remaining inputs and disable them
        document.querySelectorAll('.cell-input').forEach(input => input.disabled = true);
    } else if (attempts === guessAttemps) {
        messageElement.textContent = `Game over! The word was: ${targetWord}`;
        // Disable all inputs if game is lost
        document.querySelectorAll('.cell-input').forEach(input => input.disabled = true);
    } else {
        // Prepare for the next row
        messageElement.textContent = ''; // Clear previous messages
        currentGuessInputs = []; // Reset for the new row

        // Create inputs for the next row
        // We need to find the cells of the next row and add inputs to them
        const nextRowCells = document.querySelectorAll(`.board-row:nth-child(${attempts + 1}) .cell`);
        nextRowCells.forEach((cell, index) => {
            const input = document.createElement('input');
            input.type = 'text';
            input.maxLength = 1;
            input.classList.add('cell-input');
            input.dataset.row = attempts;
            input.dataset.col = index;
            cell.appendChild(input);
            currentGuessInputs.push(input);

            input.addEventListener('input', handleInput);
            input.addEventListener('keydown', handleKeydown);
        });

        // Focus the first input of the new current row
        if (currentGuessInputs.length > 0) {
            currentGuessInputs[0].focus();
        }
    }
}


