      ﻿<p><strong>開新檔案</strong></p>
<p>點選功能表 [ 檔案 &gt; 開新檔案 ] 即可開啟 Illustrator 新增文件的對話框，設定文件的寬度、高度、方向、色彩模式，再點選「確定」以建立新的空白文件。此外，您也可以運用 Illustrator 內建範本，或是自行建立範本以提升工作上的效率。</p>
<p align="justify"><img src="../pic/2014/IllustratorCC2014_File_New.jpg" width="545" height="467" hspace="10" galleryimg="no" /></p>
<p>&nbsp;</p>
<p><strong>從範本新增</strong></p>
<p>點選功能表 [ 檔案 &gt; 從範本新增 ] 開啟空白範本資料夾，可以從 Illustrator 提供的範本開始設計，您也可以將常用的文件儲存為範本。 </p>
<p><img src="../pic/2015/IllustratorCC2015_File_NewFromTemplate.jpg" width="800" height="550" hspace="10"  galleryimg="no"/></p>
<p>&nbsp;</p>
<p><strong>Illustrator 可置入的檔案格式</strong></p>
<p><img src="../pic/import.gif" width="250" height="370" hspace="10" galleryimg="no" /></p>
<p>置入檔案時，預設的方式是嵌入檔案。若檔案是以連結方式置入，檔原始檔案搬移位置、重新命名，或被刪除將會出現錯誤訊息，必須重新指定檔案的位置。</p>
<p>您可以利用 Illustrator 的 [ 文件資訊 ] 工具面板檢視檔案名稱、色彩模式、工作區域尺寸等資訊。</p>
<p>&nbsp;</p>
<p><strong>儲存檔案</strong></p>
<p>若您需要儲存 Illustrator 編輯的進度，點選功能表 [ 檔案 &gt; 儲存檔案 ] 開啟對話框。</p>
<p><img src="../pic/2014/IllustratorCC2014_File_Save_Options.jpg" width="466" height="656" hspace="10" galleryimg="no" /></p>
<p>您可以選擇檔案儲存的版本，讓舊版 Illustrator 也可以開啟與編輯檔案。不過新版本增加的功能（例如 IllustratorCS5 加入的透視格點），儲存到舊版格式時也不會保留，文字配置也可能發生變化。建議儲存到舊版格式時使用另存新檔，並且對存檔後的內容進行確認。</p>
<p><img src="../pic/IllustratorCS5_儲存到舊版格式.gif" width="403" height="180" galleryimg="no" /></p>
<p><strong>Illustrator 支援的檔案格式</strong></p>
<p><img src="../pic/open.gif" width="250" height="400" hspace="10" galleryimg="no" /></p>
<p>Illustrator 提供了資料復原的功能，可以將遇到當機而延誤工作進度的影響降到最低。點選功能表進入偏好設定後，選擇「檔案處理與剪貼簿」以進行設定。可依個人習慣設定自動儲存的時間，以及儲存的資料夾位置。</p>
<p><img src="../pic/2015/IllustratorCC2015_Preferences_FileHandling_Clipboard.jpg" width="697" height="595" hspace="10" galleryimg="no" /></p>
