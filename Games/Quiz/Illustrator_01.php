<p><strong>即時描圖</strong></p>
<p>Illustrator 提供的「即時描圖」，可將點陣影像快速轉換成可編輯的向量圖形。</p>
<p><strong>即時上色</strong></p>
<p>運用「即時上色」功能，在圖案的任何區域上色，並使用重疊路徑建立新形狀。讓您以直覺的方式為圖案上色，並且自動填補缺口。</p>
<p><strong>控制浮動視窗</strong></p>
<p>您可以在可區分內容的浮動視窗中，找到新增的及現有的功能。從單一位置存取可選擇的工具，可以免除使用多個浮動視窗的需要。</p>
<p><strong>自訂工作空間</strong></p>
<p>使用僅顯示特別工作所需浮動視窗的自訂工作空間，提升工作效率並最佳化螢幕區域。隨時儲存、共用或存取任何工作空間，或使用工作空間範本。</p>
<p><strong>Photoshop 圖層構圖支援</strong></p>
<p>從 Illustrator 內控制在連結、嵌入或開啟的 Photoshop 檔案中的圖層構圖可見度。</p>
<p><strong>Adobe Bridge</strong></p>
<p>Adobe Bridge 可以用來瀏覽及您的創意作品、執行自動化指令碼、存取 Adobe Stock Photos 等。</p>
<p><strong>擴充的筆畫選項</strong></p>
<p>可以選擇居中 、內部或外部來控制路徑筆畫的選項。</p>
<p><strong>行動內容的建立</strong></p>
<p>以任何 SVG 格式和其他改良的轉存選項、預視和其他功能儲存圖案，建立符合無線行動裝置的最佳化豐富圖形內容。</p>
<p><strong>灰階圖形上色</strong></p>
<p>指定特別色給連結、嵌入或開啟的灰階圖像，或甚至將特別色套用至陰影，但在列印時圖案仍會正確地分色。</p>
