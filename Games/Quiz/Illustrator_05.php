      ﻿<p><strong>物件的編輯</strong></p>
<p>您可以使用點選或拖曳圈選的方式選取物件。當物件被選取時外圍會顯示邊框與控制點，利用滑鼠拖曳可進行物件的移動、旋轉、縮放等編輯。</p>
<p>邊框的方向會因使用「旋轉」編輯而改變，需要重新調整方向時可在物件上按滑鼠右鍵，並從右鍵選單點選 [ 變形 &gt; 重設邊框 ] 或點選功能表 [ 物件 &gt; 變形 &gt; 重設邊框 ] 指令。</p>
<p><strong>移動物件</strong></p>
<p>選取物件時，使用滑鼠拖曳可以移動物件，或是按 Enter 鍵輸入移動的距離。</p>
<p><strong>複製物件</strong></p>
<p>選取物件時，按著 Alt 鍵並拖曳物件即可移動複製選取的物件。</p>
<p>製作外觀相同的物件時，也可以使用複製與貼上的功能。選取物件並點選功能表 [ 編輯 &gt; 剪下 ] 即可將物件剪下到剪貼簿，使用 [ 編輯 &gt; 拷貝 ] 則可將物件複製到剪貼簿。</p>
<p><strong>群組物件</strong></p>
<p>選取多個物件，點選功能表 [ 物件 &gt; 組成群組 ] ，物件群組後移動、旋轉、縮放的操作，皆是對整個群組進行編輯，而不是個別的物件。不過，您可以在群組的物件上按滑鼠右鍵，選擇 [ 分離選取的群組 ] ，可單獨編輯群組中的物件，編輯完成後物件會自動回復到群組的狀態。</p>
