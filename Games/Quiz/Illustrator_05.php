<p><strong>清除物件 ( Clean Up )</strong></p>
<p>文件上的孤立控制點 ( Stray Points ) 、 未上色物件 ( Unpainted Objects ) 、 空白文字路徑 ( Empty Text Paths ) ，通常是編輯時無意間留下的，儲存時會增加檔案的大小，列印時其實是不顯示的，若您確定以後不再使用可點選功能表 [ 物件 &gt; 路徑 &gt; 清除 ] 將它們清除掉。</p>
