      ﻿<p><strong>筆畫 ( Stroke ) </strong></p>
<p>利用筆畫工具面板修改路徑的筆畫效果。</p>
<p><img src="../pic/IllustratorCS5_筆畫工具面板.gif" width="515" height="362"></p>
<p>Illustrator 的視窗右側是工具面板， Illustrator  允許使用者任意組合或分離工具面板，由於工具面板數量相當多，您可以隱藏不常使用的工具面板，換取更大的工作空間。</p>
<p>&nbsp;</p>
<p><strong>導覽器 ( Navigator ) </strong></p>
<p>調整檢視比例的工具面板，可以放大縮小檢視，或是快速移動到特定的範圍。無論檢視整個版面的編排，或是編輯細部的圖形都很方便。</p>
<p><br />
    <br />
    <strong>外觀 ( Appearance ) </strong></p>
<p>外觀面板的功能是設定物件的屬性，包括填色、筆畫、特效等。</p>
<p>&nbsp;</p>
<p><strong>圖層 ( Layers )</strong></p>
<p>圖層的主要功能是物件管理，利用圖層工具面板可鎖定或隱藏圖層，或是調整圖層的順序。</p>
<p><br />
    <br />
</p>
<p>&nbsp;</p>
<p><strong>對齊 ( Align ) </strong></p>
<p> 文件上多個物件需要對齊時，對齊面板的工具可以協助您完成編輯。</p>
<p>&nbsp;</p>
<p><strong>SVG 互動 ( SVG Interactivity )</strong></p>
<p>&nbsp;</p>
<p><strong>動作 ( Actions )</strong></p>
<p>動作的功能是儲存複雜或重複使用的指令，若需要為多個物件套用相同效果時，使用動作即可進行批次處理。</p>
<p>&nbsp;</p>
<p>&nbsp;</p>
<p><strong>屬性 ( Attributes ) </strong></p>
<p>&nbsp;</p>
<p><strong>文件資訊 ( Document Info ) </strong></p>
<p>顯示目前文件的各項資訊，包括色彩模式、色彩描述檔、尺寸等資訊。</p>
<p>&nbsp;</p>
<p><strong>OpenType</strong></p>
<p>&nbsp;</p>
<p><strong>字元 ( Character ) </strong></p>
<p>設定文字的屬性，例如字型、字體級數、字元間距等。</p>
