<p><strong>筆刷 ( Brushes ) </strong></p>
<p>筆刷可以使用向量的方式繪製真實筆觸的效果，新增筆刷時可以選擇 5 種筆刷類型。</p>
<p><img src="../pic/2014/IllustratorCC2014_Brush_New.jpg" width="235" height="276" hspace="10"></p>
<p>沾水筆筆刷。</p>
<p><img src="../pic/IllustratorCS5_新增筆刷_沾水筆筆刷.gif" width="482" height="317"></p>
<p>毛刷筆刷，可以選擇不同的毛刷形狀、長度、密度、不透明度與硬度。</p>
<p><img src="../pic/IllustratorCS5_新增筆刷_毛刷筆刷.gif" width="560" height="451"></p>
<p>圖樣筆刷。</p>
<p>散落筆刷</p>
<p>必須選取物件，才可以建立散落筆刷。</p>
<p><img src="../pic/IllustratorCS5_新增筆刷_散落筆刷_01.gif" width="460" height="386" /></p>
<p>散落筆刷的特性是可以產生隨機的不規則效果。</p>
<p><img src="../pic/IllustratorCS5_新增筆刷_散落筆刷_02.gif" width="460" height="386" /></p>
<p>必須選取物件，才可以建立線條圖筆刷。</p>
<p>&nbsp;</p>
<p><strong>刪除筆刷</strong></p>
<p>您可以刪除不再使用的筆刷，注意刪除使用中的筆刷時，將會出現以下的錯誤訊息。</p>
<p><img src="../pic/2014/IllustratorCC2014_Brush_Delete.jpg" width="508" height="138" hspace="10" /></p>
<p>&nbsp;</p>
<p>您可以選擇「展開筆畫」或「移除筆畫」。</p>
<p>&nbsp;</p>
<p><strong>顏色 ( Color )</strong></p>
<p>用於物件填色或筆畫調色用的面板。 </p>
<p><strong>色票 ( Swatches ) </strong></p>
