      ﻿<p><strong>Illustrator 操作介面</strong></p>
<p><img src="../pic/2015/IllustratorCC2015_UI.jpg" width="800" height="600" hspace="10"> </p>
<p>Illustrator 上方的功能表提供主要的操作指令，包括檔案存取、物件編輯、濾鏡效果與偏好設定等。常用的指令提供了鍵盤快速鍵，若指令呈現灰色，表示在目前的狀態無法使用。</p>
<p>左側的工具箱，提供各種繪圖與編輯工具，使用滑鼠點選即可使用，右下角有三角箭頭的工具表示可切換相關的隱藏工具。</p>
<p><img src="../pic/IllustratorCS5_Tool_Select.gif" width="50" height="46" /> <strong>選取工具 Select (V)</strong></p>
<p>選取物件的工具，按著 Shift 鍵使用選取工具，可選取多個物件。</p>
<p><img src="../pic/IllustratorCS5_Tool_DirectSelection.gif" width="50" height="46" /> <strong>直接選取工具 Direct Selection (A)</strong></p>
<p>直接選取工具可選取與編輯錨點，用於修改物件的造型。</p>
<p><img src="../pic/IllustratorCS5_Tool_GroupSelection.gif" width="50" height="46" /> <strong>群組選取工具 Group Selection</strong></p>
<p>群組選取工具用於選取群組中的物件，可在不解散群組的情況下進行物件的編輯。</p>
<p><img src="../pic/IllustratorCS5_Tool_MagicWand.gif" width="50" height="46" /> <strong>魔術棒工具 Magic Wand (Y)</strong></p>
<p>魔術棒用於選取文件上擁有相同填色顏色、筆畫顏色、筆畫寬度的物件。執行 [ 視窗 > 魔術棒 ] 可以開啟魔術棒面板設定選取的容許度。</p>
